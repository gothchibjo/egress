package platform

import (
	"reflect"
	"testing"
)

const resolvConfFixture = `# generated by NetworkManager
; secondary comment
domain lan
search lan
nameserver 192.168.1.1
nameserver 8.8.8.8 # secondary resolver
nameserver 192.168.1.1
options ndots:5
`

const scutilDNSFixture = `DNS configuration

resolver #1
  search domain[0] : lan
  nameserver[0] : 192.168.1.1
  nameserver[1] : fe80::1%en0
  if_index : 14 (en0)
  flags    : Request A records

resolver #2
  nameserver[0] : 192.168.1.1
  nameserver[1] : 1.1.1.1
`

func TestParseResolvConf(t *testing.T) {
	got := parseResolvConf([]byte(resolvConfFixture))
	want := []Resolver{{Address: "192.168.1.1"}, {Address: "8.8.8.8"}}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("parseResolvConf() = %+v, want %+v", got, want)
	}
}

func TestParseResolvConfEmpty(t *testing.T) {
	for _, input := range []string{"", "domain lan\nsearch lan\n", "# nameserver 1.1.1.1\n"} {
		if got := parseResolvConf([]byte(input)); len(got) != 0 {
			t.Fatalf("parseResolvConf(%q) = %+v, want none", input, got)
		}
	}
}

func TestParseScutilDNS(t *testing.T) {
	got := parseScutilDNS(scutilDNSFixture)
	want := []Resolver{
		{Address: "192.168.1.1"},
		{Address: "fe80::1%en0"},
		{Address: "1.1.1.1"},
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("parseScutilDNS() = %+v, want %+v", got, want)
	}
}

func TestParseScutilDNSEmpty(t *testing.T) {
	got := parseScutilDNS("DNS configuration\n\nresolver #1\n  search domain[0] : lan\n")
	if len(got) != 0 {
		t.Fatalf("parseScutilDNS() = %+v, want none", got)
	}
}
